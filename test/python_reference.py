"""Regenerate numerical fixtures from the original Python package.

Usage: python3 test/python_reference.py /path/to/python/grids
Requires the source package's NumPy and PyYAML dependencies. Julia tests consume
the committed fixture and do not need Python.
"""

import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve() / "src"))
import grids


def field(name, value):
    value = np.asarray(value)
    return (
        f"{name}_shape = {list(value.shape)}\n"
        f"{name} = {value.ravel(order='F').tolist()}\n"
    )


rng = np.random.default_rng(408)
points = rng.uniform(-3.5, 3.5, (2, 31, 2))
values = rng.normal(size=(2, 31, 2, 2))
end_id = np.array([23, 17])
configs = {
    "regular": grids.RegularRectGridCfg(4, 3, 4, 3, center=(0.25, -0.5)),
    "rectangular": grids.RectangularGridCfg(
        (np.array([-2.0, -1.75, 0.0, 1.0, 3.0]), np.array([-3.0, -0.5, 0.0, 2.0]))
    ),
    "polar": grids.PolarGridCfg(
        np.array([0.25, 0.75, 1.5, 2.0, 3.0]),
        np.array([0.2, 1.0, 3.5, 5.5]),
        center=(0.25, -0.5),
    ),
}
output = ["# Generated by test/python_reference.py from the original grids package.\n"]
output += [field("points", points), field("values", values), field("end_id", end_id)]
for name, config in configs.items():
    grid = config.get_grid()
    coordinates = grid.coords(points)
    output += [f"\n[{name}]\n", field("coords", coordinates + 1)]
    for trim in (False, True):
        suffix = "interior" if trim else "full"
        output += [
            field(f"count_{suffix}", grid.count(coordinates, end_id=end_id, remove_out_of_bounds=trim)),
            field(f"sum_{suffix}", grid.sum_by_cell(values, coordinates, end_id=end_id, remove_out_of_bounds=trim)),
            field(f"mean_{suffix}", grid.mean_by_cell(values, coordinates, end_id=end_id, remove_out_of_bound=trim)),
        ]
path = pathlib.Path(__file__).parent / "fixtures" / "python_reference.toml"
path.parent.mkdir(exist_ok=True)
path.write_text("".join(output))
print(f"Wrote {path}")
